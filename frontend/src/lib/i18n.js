export function formatHMS(totalSeconds) {
  const s = Math.max(0, Math.floor(totalSeconds || 0));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = s % 60;
  const mm = String(m).padStart(2, '0');
  const ss = String(sec).padStart(2, '0');
  return h > 0 ? `${h}:${mm}:${ss}` : `${mm}:${ss}`;
}

/** Live elapsed seconds for a task row (stored + running delta). */
export function liveElapsed(task, nowMs) {
  const base = task?.elapsedSeconds || 0;
  if (task?.timerStartedAt) {
    const delta = Math.floor((nowMs - Date.parse(task.timerStartedAt)) / 1000);
    return base + Math.max(0, delta);
  }
  return base;
}

export function horizonName(h, lang) {
  if (!h) return '';
  if (lang === 'ar') return h.labelAr || h.label;
  return h.label;
}

export function horizonDesc(h, lang) {
  if (!h) return '';
  if (lang === 'ar') return h.descriptionAr || h.description;
  return h.description;
}
